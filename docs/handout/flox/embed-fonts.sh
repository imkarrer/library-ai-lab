#!/usr/bin/env bash
# Writes the `geist` Marp theme: Geist and Geist Mono as @font-face rules with the fonts
# inlined as data: URLs, read from the geist-font package in this directory's Flox
# environment. The fonts are inlined rather than linked because Marp renders a PDF through a
# temporary HTML file, where a relative url() no longer resolves, and a web font would make
# every render depend on the network.
#
#   flox/embed-fonts.sh build/geist.css
set -euo pipefail

out=${1:?usage: embed-fonts.sh OUTPUT.css}
fonts="${FLOX_ENV:?run in docs/handout with: flox activate -- make}/share/fonts/woff2"

face() {
  local family=$1 file=$2
  [ -f "$fonts/$file" ] || { echo "embed-fonts: $fonts/$file not found" >&2; exit 1; }
  printf "@font-face {\n  font-family: '%s';\n  src: url(data:font/woff2;base64,%s) format('woff2');\n  font-weight: 100 900;\n  font-style: normal;\n  font-display: block;\n}\n" \
    "$family" "$(base64 <"$fonts/$file" | tr -d '\n')"
}

mkdir -p "$(dirname "$out")"
trap 'rm -f "$out.tmp"' EXIT
{
  echo "/* @theme geist */"
  echo "/* Generated by flox/embed-fonts.sh from geist-font (SIL OFL 1.1, flox/OFL.txt). */"
  face "Geist" "Geist[wght].woff2"
  face "Geist Mono" "GeistMono[wght].woff2"
} >"$out.tmp"
mv -f "$out.tmp" "$out"
